#!/usr/bin/env python
"""Build web-ready avatar assets. Usage (from game/):
  python -I scripts/build_avatars.py --src avatars/primary --out assets/avatars
Composites RGBA portraits over theme green, crops to square, writes full (512) and thumb (160) JPGs,
avatars.json and shared/src/avatars.ts."""
import argparse, io, json, re
from pathlib import Path
from PIL import Image

LANCZOS = getattr(Image, "Resampling", Image).LANCZOS
BG = (0x0F, 0x4C, 0x37, 255)
SIZES = {"full": (512, 92), "thumb": (160, 88)}


def square(path):
    im = Image.open(path).convert("RGBA")
    # crop to a square instead of padding: portraits run off the bottom edge, so a pad strip there shows as a
    # green bar under the clothes. Wider images lose equal slices left/right; taller ones lose the bottom.
    w, h = im.size
    side = min(w, h)
    left = (w - side) // 2
    im = im.crop((left, 0, left + side, side))
    canvas = Image.new("RGBA", (side, side), BG)
    canvas.alpha_composite(im)  # alpha-correct composite over theme green
    return canvas.convert("RGB")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="avatars/primary")
    ap.add_argument("--out", default="assets/avatars")
    ap.add_argument("--ts", default=None, help="path of generated avatars.ts")
    a = ap.parse_args()
    src, out = Path(a.src), Path(a.out)
    ts = Path(a.ts) if a.ts else Path(__file__).resolve().parent.parent / "shared/src/avatars.ts"
    for d in SIZES:
        (out / d).mkdir(parents=True, exist_ok=True)
    items, rows = [], []
    for p in sorted(src.glob("*.png")):
        id_ = re.sub(r"[^a-z0-9]+", "-", p.stem.lower()).strip("-")
        label = p.stem if p.stem.isupper() and len(p.stem) <= 3 else p.stem.capitalize()
        sq = square(p)
        row = [id_, p.stat().st_size]
        for name, (px, q) in SIZES.items():
            im = sq.resize((px, px), LANCZOS) if sq.width > px else sq
            f = out / name / f"{id_}.jpg"
            im.save(f, "JPEG", quality=q, subsampling=0, optimize=True, progressive=True)
            b = io.BytesIO(); im.save(b, "PNG", optimize=True)
            w = io.BytesIO(); im.save(w, "WEBP", quality=q)
            row += [f.stat().st_size, b.tell(), w.tell()]
        rows.append(row)
        items.append({"id": id_, "label": label, "full": f"full/{id_}.jpg",
                      "thumb": f"thumb/{id_}.jpg", "width": 512, "height": 512})
    items.sort(key=lambda i: i["label"].lower())
    (out / "avatars.json").write_text(json.dumps(items, indent=2) + "\n", encoding="utf-8")
    body = ",\n".join(f'  {{ id: "{i["id"]}", label: "{i["label"]}", full: "{i["full"]}", thumb: "{i["thumb"]}" }}' for i in items)
    ts.write_text("// generated by game/scripts/build_avatars.py - do not edit\n"
                  "export const AVATARS: { id: string; label: string; full: string; thumb: string }[] = [\n"
                  + body + ",\n];\n", encoding="utf-8")
    print(f"{'id':8}{'orig':>9} | full jpg/png/webp | thumb jpg/png/webp (KB)")
    k = lambda n: f"{n/1024:7.1f}"
    for r in rows:
        print(f"{r[0]:8}{k(r[1])} | " + " ".join(k(x) for x in r[2:5]) + " | " + " ".join(k(x) for x in r[5:8]))
    print("TOTAL orig", k(sum(r[1] for r in rows)), "full jpg", k(sum(r[2] for r in rows)),
          "png", k(sum(r[3] for r in rows)), "webp", k(sum(r[4] for r in rows)),
          "| thumb jpg", k(sum(r[5] for r in rows)))

if __name__ == "__main__":
    main()
